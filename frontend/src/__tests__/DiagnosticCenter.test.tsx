const bridge = vi.hoisted(() => ({call:vi.fn(),log:vi.fn()}));
vi.mock("../api/core", () => ({coreCommand:(operation:string,...args:unknown[])=>operation.startsWith("operation_failure_log_")?bridge.log(operation,...args):bridge.call(operation,...args)}));

it("verifies a replacement provider independently of the old pending read", async () => {
  const read: WorkingRead = {schema:"archeaxis.ui-working-state/v1",workspace_id:"a".repeat(32),restore_epoch:"initial",state_revision:0,state:{drafts:{},opened_documents:[],active_document:null,page_id:null,pending_original:null},draft_digests:{},pending_document_id:null,recovery_candidates:null,recovery_requires_confirmation:false};
  const transport = async () => structuredClone(read);
  const first = new CoreWorkingStateSession({read:transport,write:transport,clearSaved:transport,recover:transport}); await first.load();
  const secondRead = {...read,workspace_id:"b".repeat(32)}, secondTransport = async () => structuredClone(secondRead);
  const second = new CoreWorkingStateSession({read:secondTransport,write:secondTransport,clearSaved:secondTransport,recover:secondTransport}); await second.load();
  let release!: (value: WorkingRead) => void;
  bridge.call.mockImplementationOnce(() => new Promise(resolve => {release = resolve;})).mockResolvedValue(structuredClone(secondRead));
  const tree = (session: CoreWorkingStateSession) => <CoreWorkingStateProvider session={session}><DiagnosticCenterTrigger/><RawReceiptButton label="旧工作区" payload={{scope:"old"}}/><DiagnosticCenter/></CoreWorkingStateProvider>;
  const view = render(tree(first)), user = userEvent.setup();
  await user.click(screen.getByRole("button",{name:/旧工作区/}));
  act(() => {window.dispatchEvent(new Event("workspace-restore-start"));window.dispatchEvent(new Event("workspace-restore-finish"));});
  expect(screen.getByRole("button",{name:"运行诊断"})).toBeDisabled();
  view.rerender(tree(second));
  await waitFor(() => expect(screen.getByRole("button",{name:"运行诊断"})).toBeEnabled());
  await user.click(screen.getByRole("button",{name:"运行诊断"}));
  expect(screen.getByRole("dialog")).toHaveTextContent("暂无诊断记录");
  await act(async () => {release(structuredClone(read));});
  expect(screen.getByRole("dialog")).not.toHaveTextContent('"old"');
  expect(bridge.call).toHaveBeenCalledTimes(2);
});
it("does not reuse a pre-restore session read or unlock from its ordinary ACK", async () => {
  const read: WorkingRead = {schema:"archeaxis.ui-working-state/v1",workspace_id:"a".repeat(32),restore_epoch:"initial",state_revision:0,state:{drafts:{},opened_documents:[],active_document:null,page_id:null,pending_original:null},draft_digests:{},pending_document_id:null,recovery_candidates:null,recovery_requires_confirmation:false};
  let release!: (value: WorkingRead) => void;
  const transport = vi.fn(async () => structuredClone(read));
  const session = new CoreWorkingStateSession({read:transport,write:transport,clearSaved:transport,recover:transport}); await session.load();
  render(<CoreWorkingStateProvider session={session}><DiagnosticCenterTrigger/><DiagnosticCenter/></CoreWorkingStateProvider>);
  transport.mockImplementationOnce(() => new Promise(resolve => {release = resolve;}));
  const old = session.load();
  bridge.call.mockRejectedValue(new Error("fresh read failed"));
  await act(async () => {window.dispatchEvent(new Event("workspace-restore-start"));window.dispatchEvent(new Event("workspace-restore-finish"));});
  expect(bridge.call).toHaveBeenCalledWith("ui_state_read");
  await act(async () => {release(structuredClone(read)); await old;});
  expect(screen.getByRole("button",{name:"运行诊断"})).toBeDisabled();
  bridge.call.mockResolvedValue(structuredClone(read));
  await userEvent.setup().click(screen.getByRole("button",{name:"重新检查诊断连接"}));
  expect(screen.getByRole("button",{name:"运行诊断"})).toBeEnabled();
});

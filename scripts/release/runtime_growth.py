_batch = ContextVar("runtime_storage_batch", default=None)


def generated_bytes(context, declared):
    """CI uses sealed actual-input evidence, never an independently editable scalar."""
    if not isinstance(context, dict) or "ci_checkpoint" not in context:
        return declared
    from scripts.release import ci_runtime_checkpoint
    _, _, forecast = ci_runtime_checkpoint.load(portable.REPO, context["paths"], context["ci_checkpoint"])
    expected = forecast["generated_bytes"]
    if declared is not None and declared != expected:
        raise ValueError("CI generated bytes differ from the sealed forecast")
    return expected


def verify_requirements(path):
    active = _batch.get()
    forecast = active.get("ci_forecast") if active is not None else None
    if forecast is not None and row(path) != {key: forecast["requirements"][key] for key in ("bytes", "sha256")}:
        raise ValueError("runtime requirements differ from the sealed CI installation inputs")


def plain(path):
    text = os.fspath(path)
    return Path(text[4:] if text.startswith("\\\\?\\") else text).absolute()


def native(path):
    return Path(portable.native(path))


def safe(path):
    path = portable.dev.safe_path(plain(path))
    for part in (*reversed(path.parents), path):
        try:
            info = native(part).lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise ValueError("linked runtime path rejected")
    return path


def row(path):
    path = safe(path)
    info = native(path).stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise ValueError("runtime donor must be an independent regular file")
    with native(path).open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    return {"bytes": info.st_size, "sha256": digest}


def core_row(path, *, repository=None):
    """Core-only admission; ordinary explicit independent donors keep their contract."""
    resources = portable.runtime_resources
    path = plain(path)
    observed = {"path": str(path)}
    try:
        safe(path)
        info = native(path).lstat()
        observed.update(resources.file_metadata(info))
        if stat.S_ISREG(info.st_mode) and info.st_nlink == 1:
            return row(path)
        repository = safe(repository if repository is not None else portable.REPO)
        cargo = portable.dev.layout(repository)["cargo_build"]
        identity = resources.core_identity(path, cargo)
        identity["cargo_core"]["repository"] = str(repository)
        print("[core-input] " + json.dumps(identity, sort_keys=True))
        return identity
    except Exception as error:
        error.add_note("Core input public lstat: " + json.dumps(observed, sort_keys=True))
        raise


def _check_core(path, identity):
    core = identity["cargo_core"]
    repository = safe(Path(core["repository"]))
    cargo = portable.dev.layout(repository)["cargo_build"]
    current = portable.runtime_resources.core_identity(path, cargo)
    current["cargo_core"]["repository"] = str(repository)
    if current != identity:
        raise ValueError("Cargo Core input changed after planning")


def interpreter_source():
    """Resolve only the running interpreter's implicit root, once per outer batch."""
    logical = Path(sys.base_prefix).absolute()
    identity = {"executable": sys.executable, "base_executable": getattr(sys, "_base_executable", None),
                "python": sys.version}
    active = _batch.get()
    bound = active.get("interpreter_binding") if active is not None else None
    if bound is not None:
        if bound["logical_root"] != str(logical) or bound["interpreter"] != identity:
            raise ValueError("implicit interpreter identity changed during runtime preparation")
        safe(Path(bound["physical_root"]))
        return bound
    physical = safe(logical.resolve(strict=True))
    executable = physical / "python.exe"
    return {"logical_root": str(logical), "physical_root": str(physical), "interpreter": identity,
            "source_python": row(executable) if native(executable).is_file() else None,
            "resolution": "CURRENT_INTERPRETER_IMPLICIT_ROOT_ONLY"}


def _interpreter_alias(path, binding):
    """One observed Windows executable alias; never a general link resolver."""
    path = plain(path)
    identity = {"executable": sys.executable, "base_executable": getattr(sys, "_base_executable", None),
                "python": sys.version}
    if (binding.get("logical_root") != str(Path(sys.base_prefix).absolute())
            or binding.get("interpreter") != identity):
        raise ValueError("runtime alias differs from the current interpreter binding")
    root = safe(Path(binding["physical_root"]))
    target = root / "python.exe"
    if path != root / "python3.exe":
        raise ValueError("unrecognized runtime executable alias")
    info = native(path).lstat()
    if (not stat.S_ISLNK(info.st_mode)
            or (os.name == "nt" and getattr(info, "st_reparse_tag", None) != 0xA000000C)):
        raise ValueError("runtime executable alias must be a file symbolic link")
    raw = os.readlink(native(path))
    lexical = plain(path.parent / raw)
    if lexical != target:
        raise ValueError("runtime executable alias must directly target its bound python.exe")
    identity = row(target)  # Strict ancestors, regular independent target, actual bytes.
    if identity != binding["source_python"]:
        raise ValueError("runtime alias target changed from the bound interpreter")
    return {**identity, "interpreter_alias": {"path": str(path), "raw_target": raw,
                                             "target": str(target), **identity}}


def snapshot(source, ignore=None, *, validate=None, interpreter_binding=None):
    source = safe(source)
    if validate is not None:
        validate(source)
    result = {}
    aliases = {}
    def fail(error):
        raise error
    for directory, dirs, files in os.walk(native(source), followlinks=False, onerror=fail):
        parent = plain(directory)
        excluded = ignore(str(parent), dirs + files) if ignore else set()
        dirs[:] = [name for name in dirs if name not in excluded]
        for name in dirs:
            safe(parent / name)
            if validate is not None:
                validate(parent / name)
        for name in files:
            if name not in excluded:
                path = parent / name
                if interpreter_binding is not None and path == source / "python3.exe":
                    info = native(path).lstat()
                    if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
                        result[path] = _interpreter_alias(path, interpreter_binding)
                        aliases[str(path)] = result[path]["interpreter_alias"]
                        continue
                if validate is not None:
                    validate(path)
                result[path] = row(path)
    if interpreter_binding is not None:
        if source != Path(interpreter_binding["physical_root"]):
            raise ValueError("runtime alias plan requires the bound physical interpreter root")
        if interpreter_binding.get("executable_aliases", aliases) != aliases:
            raise ValueError("runtime executable aliases changed after planning")
        interpreter_binding["executable_aliases"] = aliases
    return result


def copy2(source, destination, *, identity=None):
    source, destination = plain(source), safe(destination)
    state = _batch.get()
    if identity is None and state is not None:
        identity = state["inputs"].get(source)
    alias = identity.get("interpreter_alias") if identity is not None else None
    core = identity.get("cargo_core") if identity is not None else None
    if core is not None:
        if alias is not None or state is None:
            raise ValueError("Cargo Core requires one exclusive source role and an active plan")
        _check_core(source, identity)
    if alias is not None:
        if state is None or state["interpreter_binding"] is None:
            raise ValueError("runtime executable alias requires its active interpreter plan")
        if _interpreter_alias(source, state["interpreter_binding"]) != identity:
            raise ValueError("runtime executable alias changed before copy")
        incoming_source = safe(Path(alias["target"]))
    else:
        source = incoming_source = safe(source)
    if state is not None and (source not in state["inputs"] or
            (identity is not None and identity != state["inputs"][source])):
        raise ValueError("runtime donor differs from outer plan")
    if identity is None:
        if state is not None and source not in state["inputs"]:
            raise ValueError("unplanned runtime donor; preserve partial output")
        identity = state["inputs"][source] if state is not None else row(source)
    expected = {key: identity[key] for key in ("bytes", "sha256")}
    if native(incoming_source).stat().st_size != identity["bytes"]:
        raise ValueError("runtime source size changed before copy")
    if native(destination).exists() and native(destination).stat().st_nlink != 1:
        raise ValueError("linked runtime destination")
    with open(portable.native(incoming_source), "rb") as incoming, open(
            portable.native(destination), "xb" if core is not None else "wb") as outgoing:
        if core is not None and not portable.runtime_resources.opened_file_matches(incoming, core["source_metadata"]):
            raise ValueError("Cargo Core changed while opening for copy")
        remaining = identity["bytes"]
        while remaining:
            chunk = incoming.read(min(remaining, 1024 * 1024))
            if not chunk:
                raise ValueError("runtime source shorter than planned")
            outgoing.write(chunk)
            remaining -= len(chunk)
        if incoming.read(1):
            raise ValueError("runtime source grew beyond planned size")
    if row(destination) != expected:
        raise ValueError("runtime copied bytes differ")
    if alias is not None and _interpreter_alias(source, state["interpreter_binding"]) != identity:
        raise ValueError("runtime executable alias changed during copy")
    if core is not None:
        _check_core(source, identity)
    shutil.copystat(native(incoming_source), native(destination))
    return str(destination)


def copytree(source, destination, *, ignore=None, dirs_exist_ok=False, inputs=None):
    source, destination = plain(source), plain(destination)
    if inputs is None:
        state = _batch.get()
        inputs = ({path: value for path, value in state["inputs"].items() if path.is_relative_to(source)}
                  if state is not None else snapshot(source, ignore))
    copied = set()
    aliases = {path for path, value in inputs.items() if "interpreter_alias" in value}
    def copy(member, target):
        member = plain(member)
        if member not in inputs:
            raise ValueError("new runtime member after planning")
        copied.add(member)
        return copy2(member, target, identity=inputs[member])
    def ignore_aliases(directory, names):
        excluded = set(ignore(directory, names)) if ignore else set()
        # Never let shutil traverse this link, including if it is retargeted to a
        # directory after planning. Materialize it through bounded copy2 below.
        excluded.update(path.name for path in aliases if path.parent == plain(directory))
        return excluded
    result = shutil.copytree(native(source), native(destination), ignore=ignore_aliases,
                             copy_function=copy, dirs_exist_ok=dirs_exist_ok)
    for alias in sorted(aliases):
        copy(alias, destination / alias.relative_to(source))
    if copied != set(inputs):
        raise ValueError("runtime member disappeared after planning")
    return result


@contextmanager
def batch(destination, inputs, total, context=None, *, unknown_output=False, interpreter_binding=None):
    """Nested preparation shares the outer review; no rolling checkpoint or bypass."""
    outer = _batch.get()
    if outer is not None:
        if total > outer["total"]:
            raise ValueError("nested runtime plan exceeds reviewed projection")
        yield
        return
    if type(total) is not int or total < 0 or (unknown_output and total == 0):
        raise ValueError("runtime planned bytes must be explicit and positive for unknown generation")
    state = None
    ci_forecast = None
    if isinstance(context, dict) and "ci_checkpoint" in context:
        from scripts.release import ci_runtime_checkpoint
        _, _, ci_forecast = ci_runtime_checkpoint.load(portable.REPO, context["paths"], context["ci_checkpoint"])
        if total < ci_forecast["generated_bytes"] + sum(value["bytes"] for value in inputs.values()):
            raise ValueError("CI projection omits known inputs or the sealed generated forecast")
    token = _batch.set({"inputs": inputs, "total": total, "interpreter_binding": interpreter_binding,
                        "ci_forecast": ci_forecast})
    try:
        if total >= portable.LARGE_COPY_BYTES or unknown_output:
            state = portable._storage_pre(Path(destination), total, context, formal_runtime=True)
            state["producer"] = "runtime-staging"
            state["interpreter_binding"] = interpreter_binding
            state["core_inputs"] = {str(path): identity for path, identity in inputs.items() if "cargo_core" in identity}
            state["projection_scope"] = "known copy bytes plus caller-declared generated-byte estimate; not a hard quota"
            if any(state[key]["status"] == "REVIEW_REQUIRED" for key in ("pre_review", "projected_review")):
                raise portable.GrowthReviewRequiredError("runtime storage growth requires review")
            state["copy_outcome"] = "STARTED"
        yield
        if state is not None:
            state["copy_outcome"] = "PRODUCER_COMPLETED"
    finally:
        error = sys.exc_info()[1]
        try:
            if state is not None:
                portable._storage_post(state, error)
        finally:
            _batch.reset(token)

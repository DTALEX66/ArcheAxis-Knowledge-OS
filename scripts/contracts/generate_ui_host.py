"""Generate the finite UI-host Rust/TS contract from one schema; --check never writes."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "packages/contracts/v2/ui-host.schema.json"


def generate():
    raw = SOURCE.read_bytes()
    schema = json.loads(raw)
    response_raw = (ROOT / schema["x-response-source"]).read_bytes()
    response_defs = json.loads(response_raw)["$defs"]
    digest = hashlib.sha256(raw + b"\0" + response_raw).hexdigest()
    operations = schema["x-operations"]
    assert list(operations) == schema["$defs"]["Operation"]["enum"]
    existing = json.loads((ROOT / "packages/contracts/v1/core-command.schema.json").read_text(encoding="utf-8"))["properties"]["operation"]["enum"]
    assert all(value is None or value in existing for value in operations.values())
    variant = lambda name: "".join(part.capitalize() for part in name.split("."))
    rust = '// Generated by scripts/contracts/generate_ui_host.py. Do not edit.\nuse serde::{Deserialize, Serialize};\n'
    rust += f'pub const CONTRACT_DIGEST: &str = "{digest}";\n'
    rust += 'pub const CORE_RESPONSE_SCHEMAS: &str = ' + 'r###"' + json.dumps({op:response_defs[name] for op,name in schema["x-response-definitions"].items()}, separators=(",", ":")) + '"###;\n'
    rust += '#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]\npub enum Operation {\n'
    rust += "".join(f'    #[serde(rename = "{name}")]\n    {variant(name)},\n' for name in operations)
    rust += '}\nimpl Operation {\n    pub fn core_operation(&self) -> Option<&\'static str> {\n        match self {\n'
    rust += "".join(f'            Self::{variant(name)} => ' + (f'Some("{mapped}")' if mapped else 'None') + ',\n' for name, mapped in operations.items())
    rust += '''        }
    }
}
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct EmptyInput {}
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Request {
    pub schema: String,
    pub contract_digest: String,
    pub request_id: String,
    pub workspace_id: String,
    pub restore_epoch: String,
    pub operation: Operation,
    pub input: EmptyInput,
}
impl Request {
    pub fn validate(&self) -> Result<(), &'static str> {
        let hex = |value: &str, len: usize| value.len() == len && value.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
        if self.schema != "archeaxis.ui-host-request/v2" || self.contract_digest != CONTRACT_DIGEST { return Err("HOST_VERSION_INCOMPATIBLE"); }
        if self.request_id.is_empty() || self.request_id.len() > 64 || !self.request_id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_') || !hex(&self.workspace_id, 32) || !(self.restore_epoch == "initial" || hex(&self.restore_epoch, 32)) { return Err("HOST_REQUEST_INVALID"); }
        Ok(())
    }
}
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Outcome { ReadOk, Unavailable, Rejected, Unknown }
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct BuildIdentity { pub host_version: String, pub source_revision: Option<String> }
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Response {
    pub schema: String,
    pub contract_digest: String,
    pub request_id: String,
    pub workspace_id: String,
    pub restore_epoch: String,
    pub operation: Operation,
    pub outcome: Outcome,
    pub reason_code: Option<String>,
    pub core_status: Option<u16>,
    pub build_identity: BuildIdentity,
    pub checked_at: u64,
    pub result_ref: Option<serde_json::Value>,
}
'''
    ts = '// Generated by scripts/contracts/generate_ui_host.py. Do not edit.\n'
    ts += f'export const UI_HOST_CONTRACT_DIGEST = "{digest}" as const;\n'
    ts += 'export const UI_HOST_OPERATIONS = ' + json.dumps(list(operations)) + ' as const;\n'
    ts += 'export const UI_HOST_MAPPING = ' + json.dumps(operations) + ' as const;\n'
    ts += '''export type UiHostOperation = typeof UI_HOST_OPERATIONS[number];
export type UiHostRequest = {schema:"archeaxis.ui-host-request/v2";contract_digest:string;request_id:string;workspace_id:string;restore_epoch:string;operation:UiHostOperation;input:Record<string,never>};
export type UiHostResponse = {schema:"archeaxis.ui-host-response/v2";contract_digest:string;request_id:string;workspace_id:string;restore_epoch:string;operation:UiHostOperation;outcome:"READ_OK"|"UNAVAILABLE"|"REJECTED"|"UNKNOWN";reason_code:null|"HOST_CONTRACT_MISSING"|"WORKSPACE_CHANGED"|"RESULT_UNKNOWN"|"CORE_REJECTED"|"CORE_UNAVAILABLE"|"INVALID_CORE_RESULT";core_status:number|null;build_identity:{host_version:string;source_revision:null};checked_at:number;result_ref:Record<string,unknown>|null};
function object(value:unknown):value is Record<string,unknown>{return !!value&&typeof value==="object"&&!Array.isArray(value);}
export function assertUiHostRequest(value:unknown):asserts value is UiHostRequest {
 if(!object(value)||Object.keys(value).sort().join()!=="contract_digest,input,operation,request_id,restore_epoch,schema,workspace_id"||value.schema!=="archeaxis.ui-host-request/v2"||value.contract_digest!==UI_HOST_CONTRACT_DIGEST||typeof value.request_id!=="string"||!/^[A-Za-z0-9_-]{1,64}$/.test(value.request_id)||typeof value.workspace_id!=="string"||!/^[a-f0-9]{32}$/.test(value.workspace_id)||typeof value.restore_epoch!=="string"||!/^(initial|[a-f0-9]{32})$/.test(value.restore_epoch)||!UI_HOST_OPERATIONS.includes(value.operation as UiHostOperation)||!object(value.input)||Object.keys(value.input).length)throw new Error("HOST_REQUEST_INVALID");
}
export function assertUiHostResponse(value:unknown,request:UiHostRequest):asserts value is UiHostResponse {
 if(!object(value)||Object.keys(value).sort().join()!=="build_identity,checked_at,contract_digest,core_status,operation,outcome,reason_code,request_id,restore_epoch,result_ref,schema,workspace_id"||value.schema!=="archeaxis.ui-host-response/v2"||value.contract_digest!==UI_HOST_CONTRACT_DIGEST||value.request_id!==request.request_id||value.workspace_id!==request.workspace_id||value.restore_epoch!==request.restore_epoch||value.operation!==request.operation||!object(value.build_identity)||Object.keys(value.build_identity).sort().join()!=="host_version,source_revision"||typeof value.build_identity.host_version!=="string"||!value.build_identity.host_version||value.build_identity.source_revision!==null||!Number.isSafeInteger(value.checked_at)||Number(value.checked_at)<0||!(value.core_status===null||(Number.isInteger(value.core_status)&&Number(value.core_status)>=100&&Number(value.core_status)<=599)))throw new Error("HOST_RESPONSE_INVALID");
 const failures=["HOST_CONTRACT_MISSING","WORKSPACE_CHANGED","RESULT_UNKNOWN","CORE_REJECTED","CORE_UNAVAILABLE","INVALID_CORE_RESULT"];
 if(value.outcome==="READ_OK") {
  if(!UI_HOST_MAPPING[request.operation]||value.reason_code!==null||!object(value.result_ref)||!(Number(value.core_status)>=200&&Number(value.core_status)<300))throw new Error("HOST_RESPONSE_INVALID");
 } else if(!["UNAVAILABLE","REJECTED","UNKNOWN"].includes(String(value.outcome))||!failures.includes(String(value.reason_code))||value.result_ref!==null)throw new Error("HOST_RESPONSE_INVALID");
}
'''
    rust = re.sub(r"(?m)^(pub const|#\[derive|impl )", r"#[rustfmt::skip]\n\1", rust)
    return {ROOT / "crates/archeaxis-contracts/src/generated/ui_host.rs": rust,
            ROOT / "frontend/src/api/generated/ui-host-contract.ts": ts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = []
    for path, content in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if drift:
        print("UI host contract drift: " + ", ".join(drift))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

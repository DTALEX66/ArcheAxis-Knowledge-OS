"""Generate the project-owned finite conversation consumer contract."""
import json
import sys
from pathlib import Path
from generate_core_document import ts
ROOT = Path(__file__).resolve().parents[2]
schema = json.loads((ROOT/'packages/contracts/v2/conversation.schema.json').read_text(encoding='utf8'))
result = '// Generated by scripts/contracts/generate_conversation.py\n'+'\n'.join(f'export type {name} = {ts(node)};' for name,node in schema['$defs'].items())+'\n'
target=ROOT/'frontend/src/api/generated/conversation.ts'
if '--check' in sys.argv:
    raise SystemExit(0 if target.is_file() and target.read_text(encoding='utf8')==result else 1)
target.write_text(result,encoding='utf8')

"""从既有严格Handoff及本机preview/snapshot规范生成消费合同。"""

import argparse
import json
from pathlib import Path

from generate_core_document import ts as core_ts

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "frontend/src/api/generated/project-handoff.ts"


def ts(node):
    if "oneOf" in node:
        return " | ".join(ts(child) for child in node["oneOf"])
    if "allOf" in node:
        return ts(node["allOf"][0])
    if node.get("type") == "object":
        required = node.get("required", [])
        fields = "; ".join(
            f"{key}{'' if key in required else '?'}: {ts(value)}"
            for key, value in node.get("properties", {}).items()
        )
        return "{ " + fields + " }"
    if node.get("type") == "array":
        return f"Array<{ts(node['items'])}>"
    return core_ts(node)


def generate():
    folder = ROOT / "packages/contracts/v2"
    base = json.loads((folder / "project-handoff.schema.json").read_text(encoding="utf-8"))
    definitions = base.pop("$defs")
    definitions["Handoff"] = base
    for name, file in [
        ("Preview", "project-handoff-preview.schema.json"),
        ("Snapshot", "project-handoff-snapshot.schema.json"),
    ]:
        definitions[name] = json.loads((folder / file).read_text(encoding="utf-8"))

    def local(node):
        if isinstance(node, list):
            return [local(child) for child in node]
        if not isinstance(node, dict):
            return node
        result = {key: local(value) for key, value in node.items()}
        ref = result.get("$ref", "")
        if ref == "project-handoff.schema.json":
            result["$ref"] = "#/$defs/Handoff"
        elif ref.startswith("project-handoff.schema.json#/"):
            result["$ref"] = ref.split(".json", 1)[1]
        return result

    definitions = local(definitions)
    out = "// Generated by scripts/contracts/generate_project_handoff.py; edit canonical JSON Schema.\n"
    out += (
        "\n".join(f"export type {name} = {ts(node)};" for name, node in definitions.items()) + "\n"
    )
    out += (
        "const definitions: Record<string, any> = "
        + json.dumps(definitions, ensure_ascii=False)
        + ";\n"
    )
    out += """
function valid(node: any, value: unknown): boolean {
  if (!node) return false;
  if (node.$ref) return valid(definitions[node.$ref.split('/').pop()], value);
  if ('const' in node && value !== node.const) return false;
  if (node.enum && !node.enum.includes(value)) return false;
  if (node.allOf && !node.allOf.every((x: any) => valid(x, value))) return false;
  if (node.oneOf && node.oneOf.filter((x: any) => valid(x, value)).length !== 1) return false;
  if (node.type === 'string' && (typeof value !== 'string' ||
      (node.minLength !== undefined && [...value].length < node.minLength) ||
      (node.maxLength !== undefined && [...value].length > node.maxLength) ||
      (node.pattern && !new RegExp(node.pattern.replace(/\\$$/, '(?![\\\\s\\\\S])')).test(value)))) return false;
  if (node.type === 'integer' && (typeof value !== 'number' || !Number.isSafeInteger(value) ||
      (node.minimum !== undefined && value < node.minimum) || (node.maximum !== undefined && value > node.maximum))) return false;
  if (node.type === 'boolean' && typeof value !== 'boolean') return false;
  if (node.type === 'array' && (!Array.isArray(value) ||
      (node.minItems !== undefined && value.length < node.minItems) ||
      (node.maxItems !== undefined && value.length > node.maxItems) || !value.every(x => valid(node.items, x)))) return false;
  if (node.type === 'object' || node.properties) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
    const record = value as Record<string, unknown>;
    if (!(node.required || []).every((key: string) => Object.hasOwn(record, key))) return false;
    if (node.additionalProperties === false && Object.keys(record).some(key => !Object.hasOwn(node.properties || {}, key))) return false;
    if (!Object.entries(node.properties || {}).every(([key, child]) => !Object.hasOwn(record, key) || valid(child, record[key]))) return false;
  }
  return true;
}
export function assertHandoffDto<T>(name: 'Handoff' | 'Preview' | 'Snapshot', value: unknown): T {
  if (!valid(definitions[name], value)) throw new Error('上下文引用格式不兼容，未打开正文。');
  return value as T;
}
"""
    return out


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != result:
            raise SystemExit("project-handoff generated DTO drift")
    else:
        TARGET.write_text(result, encoding="utf-8", newline="\n")

"""Generate material context DTOs from the admitted schema."""
import json
import sys
from pathlib import Path
from generate_core_document import ts
ROOT = Path(__file__).resolve().parents[2]
schema = json.loads((ROOT / 'packages/contracts/v2/material-question.schema.json').read_text())
result = '// Generated by scripts/contracts/generate_material_question.py\n' + '\n'.join(f'export type {name} = {ts(node)};' for name, node in schema['$defs'].items()) + '\n'
result += "const definitions: Record<string, any> = " + json.dumps(schema['$defs'], ensure_ascii=False) + ";\n"
result += r"""
function valid(node: any, value: unknown): boolean {
  if (node.$ref) return valid(definitions[node.$ref.split('/').pop()], value);
  if ('const' in node) return value === node.const;
  if (node.anyOf) return node.anyOf.some((n: any) => valid(n, value));
  if (node.enum) return node.enum.includes(value);
  if (Array.isArray(node.type)) return node.type.some((type: string) => valid({...node, type}, value));
  switch (node.type) {
    case 'string': return typeof value === 'string' && (node.minLength === undefined || [...value].length >= node.minLength)
      && (node.maxLength === undefined || [...value].length <= node.maxLength) && (node.pattern === undefined || new RegExp(node.pattern).test(value));
    case 'integer': return typeof value === 'number' && Number.isSafeInteger(value)
      && (node.minimum === undefined || value >= node.minimum) && (node.maximum === undefined || value <= node.maximum);
    case 'number': return typeof value === 'number' && Number.isFinite(value);
    case 'boolean': return typeof value === 'boolean';
    case 'null': return value === null;
    case 'array': return Array.isArray(value) && (node.minItems === undefined || value.length >= node.minItems)
      && (node.maxItems === undefined || value.length <= node.maxItems) && value.every(v => valid(node.items, v));
    case 'object': {
      if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
      const r = value as Record<string, unknown>;
      return (node.required || []).every((k: string) => k in r)
        && (node.additionalProperties !== false || Object.keys(r).every(k => k in (node.properties || {})))
        && Object.entries(node.properties || {}).every(([k,n]) => !(k in r) || valid(n,r[k]));
    }
    default: return false;
  }
}
export function assertMaterialQuestionDto<T>(name: string, value: unknown): T {
  if (!definitions[name] || !valid(definitions[name], value)) throw new Error('MATERIAL_DTO_INVALID: ' + name);
  return value as T;
}
"""
target = ROOT / 'frontend/src/api/generated/material-question.ts'
if '--check' in sys.argv:
    raise SystemExit(0 if target.is_file() and target.read_text() == result else 1)
target.write_text(result, encoding='utf8', newline='\n')
